#RADAR CHART
import pandas as pd
import matplotlib.pyplot as plt
import numpy as np
file_path = "/content/smartphones-selected-columns(1).csv"
df = pd.read_csv(file_path)
data = df.dropna(
    subset=[
        "rating_score",
        "ram_gb",
        "storage_gb",
        "core_count",
        "clock_speed_ghz"
    ]
).copy()
# Select the top 5 rated smartphones
top_5 = data.sort_values(
    by="rating_score",
    ascending=False
).head(5)
# Features for radar chart
features = [
    "rating_score",
    "ram_gb",
    "storage_gb",
    "core_count",
    "clock_speed_ghz"
]
feature_labels = [
    "Rating",
    "RAM (GB)",
    "Storage (GB)",
    "Cores",
    "Clock Speed (GHz)"
]
# Normalize each feature from 0 to 1
normalized = top_5[features].copy()
for column in features:
    minimum = normalized[column].min()
    maximum = normalized[column].max()

    if maximum != minimum:
        normalized[column] = (
            normalized[column] - minimum
        ) / (maximum - minimum)
    else:
        normalized[column] = 1
# Radar angles
angles = np.linspace(
    0,
    2 * np.pi,
    len(features),
    endpoint=False
).tolist()
angles += angles[:1]
# Create radar chart
fig, ax = plt.subplots(
    figsize=(9, 9),
    subplot_kw=dict(polar=True)
)
# Plot each smartphone
for i in range(len(top_5)):
    values = normalized.iloc[i].tolist()
    values += values[:1]
    phone_name = str(top_5.iloc[i]["smartphone"])
    ax.plot(
        angles,
        values,
        linewidth=2,
        label=phone_name
    )
    ax.fill(
        angles,
        values,
        alpha=0.08
    )
# Labels
ax.set_xticks(angles[:-1])
ax.set_xticklabels(feature_labels)
ax.set_title(
    "Top 5 Rated Smartphones - Feature Comparison",
    fontsize=15,
    fontweight="bold"
)
ax.legend(
    loc="upper right",
    bbox_to_anchor=(1.35, 1.15)
)
plt.show()

