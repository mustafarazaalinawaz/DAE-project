#CANDLESTICK GRAPH
import pandas as pd
import matplotlib.pyplot as plt
from matplotlib.patches import Rectangle
file_path = "/content/smartphones-selected-columns(1).csv"
df = pd.read_csv(file_path)
df.columns = df.columns.astype(str).str.strip()
data = df.dropna(subset=["price_inr"]).copy()

# Convert price to numeric
data["price_inr"] = pd.to_numeric(
    data["price_inr"],
    errors="coerce"
)

data = data.dropna(subset=["price_inr"])

# Sort by price
data = data.sort_values("price_inr").reset_index(drop=True)

# ============================================================
# 3. DIVIDE SMARTPHONES INTO 10 PRICE GROUPS
# ============================================================

data["price_group"] = pd.qcut(
    data["price_inr"],
    q=10,
    duplicates="drop"
)

# ============================================================
# 4. CALCULATE OPEN, HIGH, LOW, CLOSE
# ============================================================

candlestick_data = []

for group, group_data in data.groupby(
    "price_group",
    observed=True
):

    prices = group_data["price_inr"].values

    if len(prices) > 0:

        open_price = prices[0]
        close_price = prices[-1]
        high_price = prices.max()
        low_price = prices.min()

        candlestick_data.append([
            open_price,
            high_price,
            low_price,
            close_price
        ])

# ============================================================
# 5. CREATE CANDLESTICK GRAPH
# ============================================================

fig, ax = plt.subplots(figsize=(12, 7))

for i, candle in enumerate(candlestick_data):

    open_price = candle[0]
    high_price = candle[1]
    low_price = candle[2]
    close_price = candle[3]

    # Draw high-low line
    ax.plot(
        [i, i],
        [low_price, high_price],
        linewidth=2
    )

    # Determine candle direction
    bottom = min(open_price, close_price)
    height = abs(close_price - open_price)

    # Make sure a visible body exists
    if height == 0:
        height = high_price * 0.005

    # Draw candle body
    rectangle = Rectangle(
        (i - 0.3, bottom),
        0.6,
        height,
        fill=False,
        linewidth=2
    )

    ax.add_patch(rectangle)
# ============================================================
# 6. LABELS
# ============================================================
ax.set_title(
    "Smartphone Price Distribution - Candlestick Chart",
    fontsize=16,
    fontweight="bold"
)
ax.set_xlabel("Price Group")
ax.set_ylabel("Price (INR)")
ax.set_xticks(range(len(candlestick_data)))
ax.set_xticklabels(
    [f"Group {i+1}" for i in range(len(candlestick_data))]
)
ax.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()